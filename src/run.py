from graph import build_graph

graph = build_graph()

# graph.invoke 안에 들어가는 값은 시작 상태값임
# trip_id 와 log 는 시작상태값으로 넣어주어야 한다. (log는 빈 리스트로 시작)
# 나머지값은 노드들이 함수를 실행하면서 채워나간다. (receipts, total, report)

# ollama 의 콜드 스타트 -> 첫 실행은 매우 오래걸린다.
result = graph.invoke({"trip_id": "T-2026-03", "log": []})  # 빈 리스트 명시 - list 타입 리듀서의 첫번째 값을 빈 리스트로 시작할 수 있어서, 이 값을 빼도 동작을 한다. 다만 첫 실행에서는 기록이 비어있다는 의미로 넣어둠

print("합계:", result["total"])
print("보고:", result["report"])
print("기록:")
for line in result["log"]:
    print(" -", line)



